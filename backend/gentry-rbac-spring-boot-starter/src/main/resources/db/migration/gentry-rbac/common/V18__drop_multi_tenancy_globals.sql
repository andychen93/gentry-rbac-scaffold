-- V18 拿掉多租户 · 第二步：删平台级标记列、删租户表
--
-- 详见 doc/design/modules/core/去多租户化-概要设计.md
--
-- 这两处删除不涉及任何索引（is_platform 无索引；sys_tenant 无被引用的外键——
-- 本仓库不用数据库级 FK 约束），三库语法完全一致，不需要按方言拆分。
-- tenant_id 列的删除因为要先处理索引，拆到 V19 的三个方言目录里。
-- =============================================

-- ---------------------------------------------
-- 1. sys_menu 去掉"平台级"标记
--
-- V14/V15 引入 is_platform 是为了区分"平台超管专属 vs 租户管理员可持有"的权限点。
-- 去掉多租户后只剩一种管理员，这个区分不再有意义。
-- ---------------------------------------------
ALTER TABLE sys_menu DROP COLUMN is_platform;

-- ---------------------------------------------
-- 2. 删除租户表本身
--
-- V17 已经清理完所有引用租户角色/菜单的数据，这里删表不会留下悬空引用。
-- ---------------------------------------------
DROP TABLE sys_tenant;
